/**
 * Build the food guide index: merge data/food-guide/_parts/<slug>-*.json into
 * data/food-guide/<slug>.json, check every file against the schema, and write
 * src/lib/foodGuide/generated.ts (metadata for the hub + lazy loaders).
 * Run: npx tsx scripts/food-guide-index.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { checkCity, checkTopic } from "../src/lib/foodGuide/check";
import type { FoodCity, FoodCityMeta, FoodTopic, FoodTopicMeta } from "../src/lib/foodGuide/types";

const ROOT = join(__dirname, "..");
const DIR = join(ROOT, "data", "food-guide");
const PARTS = join(DIR, "_parts");
const TOPICS = join(DIR, "topics");
const OUT = join(ROOT, "src", "lib", "foodGuide", "generated.ts");

const read = <T>(p: string) => JSON.parse(readFileSync(p, "utf8")) as T;
const bases = read<{ slug: string; region: string }[]>(join(ROOT, "data", "bases.json"));
const regionOf = new Map(bases.map((b) => [b.slug, b.region]));

// 1. Merge parts (e.g. tokyo-core.json + tokyo-places.json) into one city file.
if (existsSync(PARTS)) {
  const groups = new Map<string, string[]>();
  for (const f of readdirSync(PARTS).filter((f) => f.endsWith(".json"))) {
    const slug = f.replace(/-[^-]+\.json$/, "");
    groups.set(slug, [...(groups.get(slug) ?? []), f]);
  }
  for (const [slug, files] of groups) {
    const merged = files.sort().reduce<Partial<FoodCity>>((acc, f) => ({ ...acc, ...read<Partial<FoodCity>>(join(PARTS, f)) }), {});
    if (!merged.slug || !merged.name) continue; // the core part hasn't landed yet
    const ordered: FoodCity = { slug: merged.slug, name: merged.name, ...merged } as FoodCity;
    writeFileSync(join(DIR, `${slug}.json`), JSON.stringify(ordered, null, 2) + "\n");
  }
}

// 2. Check and index.
const problems: string[] = [];
const cities: FoodCityMeta[] = [];
for (const f of readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()) {
  const c = read<FoodCity>(join(DIR, f));
  problems.push(...checkCity(c, f));
  if (!regionOf.has(c.slug)) problems.push(`${f}: slug "${c.slug}" is not in data/bases.json`);
  cities.push({
    slug: c.slug,
    name: c.name,
    region: regionOf.get(c.slug) ?? "",
    tagline_pt: c.tagline_pt ?? "",
    counts: { meibutsu: c.meibutsu?.length ?? 0, areas: c.areas?.length ?? 0, places: c.places?.length ?? 0, shops: c.shops?.length ?? 0 },
  });
}
const topics: FoodTopicMeta[] = [];
if (existsSync(TOPICS)) {
  for (const f of readdirSync(TOPICS).filter((f) => f.endsWith(".json")).sort()) {
    const t = read<FoodTopic>(join(TOPICS, f));
    problems.push(...checkTopic(t, `topics/${f}`));
    topics.push({ slug: t.slug, title_pt: t.title_pt, items: t.sections.reduce((n, s) => n + (s.items?.length ?? 0), 0) });
  }
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

// Bases order (Tokyo first, then the catalog's geographic order).
const order = new Map(bases.map((b, i) => [b.slug, i]));
cities.sort((a, b) => (order.get(a.slug) ?? 99) - (order.get(b.slug) ?? 99));

const src = `// Generated by scripts/food-guide-index.ts. Do not edit.
import type { FoodCity, FoodCityMeta, FoodTopic, FoodTopicMeta } from "./types";

export const FOOD_CITIES: FoodCityMeta[] = ${JSON.stringify(cities, null, 2)};

export const FOOD_TOPICS: FoodTopicMeta[] = ${JSON.stringify(topics, null, 2)};

export const CITY_LOADERS: Record<string, () => Promise<FoodCity>> = {
${cities.map((c) => `  ${JSON.stringify(c.slug)}: () => import("../../../data/food-guide/${c.slug}.json").then((m) => m.default as FoodCity),`).join("\n")}
};

export const TOPIC_LOADERS: Record<string, () => Promise<FoodTopic>> = {
${topics.map((t) => `  ${JSON.stringify(t.slug)}: () => import("../../../data/food-guide/topics/${t.slug}.json").then((m) => m.default as FoodTopic),`).join("\n")}
};
`;
writeFileSync(OUT, src);
console.log(`food guide: ${cities.length} cities, ${topics.length} topics`);
